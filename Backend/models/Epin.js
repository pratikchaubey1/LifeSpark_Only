const mongoose = require('mongoose');

const epinSchema = new mongoose.Schema({
    code: { type: String, required: true, unique: true },
    ownerUserId: { type: String, default: null }, // User ID who owns this pin
    used: { type: Boolean, default: false },
    usedByUserId: { type: String, default: null }, // User ID who used this pin
    usedAt: { type: Date, default: null },
    packageId: { type: String, default: null }, // e.g., 'Basic', 'Standard'
    transferredAt: { type: Date, default: null },
    transferredBy: { type: String, default: null }, // User ID who transferred
    isSelfGenerated: { type: Boolean, default: false }, // Generated by member from balance
    pinTag: { type: String, default: 'ADMIN' }, // 'ADMIN' or 'SELF-GENERATED'
    generatedByUserId: { type: String, default: null }, // Member who bought/generated it
    cost: { type: Number, default: 1650 }, // Cost deducted (default 1650: 1500 + 10% fee)
    activatedUserId: { type: String, default: null } // User activated with this pin
}, {
    timestamps: true, // Adds createdAt and updatedAt
    collection: 'epins'
});

// Indexes for performance
epinSchema.index({ ownerUserId: 1 });
epinSchema.index({ used: 1 });
epinSchema.index({ ownerUserId: 1, used: 1 }); // Compound index for owner + availability queries
epinSchema.index({ isSelfGenerated: 1 });
epinSchema.index({ generatedByUserId: 1 });

module.exports = mongoose.model('Epin', epinSchema);
